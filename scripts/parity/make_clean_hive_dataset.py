#!/usr/bin/env python
"""Produce a clean meta-tagging dataset ready for manual Hive import.

The UAT snapshot at ``build/meta-tagging/`` carries paired columns per
table: each clean-named column (``first_name``) has a synthetic twin
(``attr_1_1_1_9_2_1``) whose name encodes the ground-truth code.  That
pairing is a *synth-generator artifact*, not a production schema, and
it:

  * leaks the ground truth into anything that reads the twin's name;
  * creates a column the LLM-only pipeline would never meaningfully
    classify (the name *is* the answer).

This script emits a cleaned copy suitable for Hive CREATE TABLE /
INSERT — obfuscated twin columns dropped, table-name prefix stripped
from headers (``business_data.first_name`` → ``first_name``).

Output:

    build/meta-tagging-clean/
      README.md                        (provenance + cleaning rules)
      annotations.csv                  (vocabulary, verbatim from UAT)
      <table>.csv × 8                  (clean columns only, stripped headers)
    build/meta-tagging-clean.zip       (same, zipped for hand-off)

Re-run idempotently.  Nothing leaves ``build/`` so annotations.csv and
the labeled tables stay out of git.
"""

from __future__ import annotations

import csv
import logging
import re
import shutil
import sys
import zipfile
from pathlib import Path


log = logging.getLogger("clean_hive_dataset")

_OBFUSCATED_PREFIXES = ("attr", "field", "key", "code", "var", "ref",
                        "data", "col")
_OBFUSCATED_RE = re.compile(
    r"^(?:" + "|".join(_OBFUSCATED_PREFIXES) + r")_\d+(?:_\d+)*$"
)


def _strip_table_prefix(header: list[str], table_name: str) -> list[str]:
    """Drop a uniform ``<table>.`` prefix on every column header."""
    prefix = f"{table_name}."
    if all(h.startswith(prefix) for h in header if h):
        return [h[len(prefix):] for h in header]
    return header


def _clean_table(src: Path, dst: Path) -> tuple[int, int]:
    """Copy one CSV with obfuscated columns dropped and headers stripped.

    Returns (kept_columns, dropped_columns).
    """
    with open(src, newline="") as f:
        reader = csv.reader(f)
        header = next(reader, None)
        rows = list(reader)
    if not header:
        return (0, 0)

    stripped = _strip_table_prefix(header, src.stem)
    keep_idx = [i for i, name in enumerate(stripped)
                if not _OBFUSCATED_RE.match(name)]
    dropped = len(stripped) - len(keep_idx)

    with open(dst, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow([stripped[i] for i in keep_idx])
        for row in rows:
            writer.writerow([row[i] if i < len(row) else "" for i in keep_idx])

    return (len(keep_idx), dropped)


def main() -> int:
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
        stream=sys.stderr,
    )

    src_dir = Path("build/meta-tagging").resolve()
    if not (src_dir / "annotations.csv").is_file():
        log.error("missing %s/annotations.csv", src_dir)
        return 1

    out_dir = Path("build/meta-tagging-clean").resolve()
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)

    # 1. annotations.csv — verbatim.  (The Hive export already has
    # ``annotations.<col>`` headers which Hive imports unchanged;
    # stripping the prefix here would desync from the CREATE TABLE
    # statement UAT already uses for the vocabulary table.)
    shutil.copyfile(src_dir / "annotations.csv", out_dir / "annotations.csv")

    # 2. data CSVs — drop obfuscated cols, strip table-name prefix.
    table_csvs = sorted(p for p in src_dir.glob("*.csv")
                        if p.name != "annotations.csv")
    totals: list[tuple[str, int, int]] = []
    for src in table_csvs:
        dst = out_dir / src.name
        kept, dropped = _clean_table(src, dst)
        totals.append((src.name, kept, dropped))
        log.info("  %s: kept=%d dropped=%d", src.name, kept, dropped)

    # 3. README.md with provenance.
    readme_lines = [
        "# Meta-tagging UAT corpus — leak-sanitized for LLM/ML comparison",
        "",
        "Generated by ``scripts/parity/make_clean_hive_dataset.py``. Source "
        "is the UAT snapshot at ``build/meta-tagging/`` (2026-04-18). This "
        "cleaned copy is drop-in for Hive CREATE TABLE / INSERT — header "
        "table-name prefixes stripped, synthetic obfuscated paired columns "
        "removed.",
        "",
        "## What changed vs. the UAT source",
        "",
        "For every data CSV (all eight tables):",
        "",
        "1. **Stripped** the ``<table_name>.`` prefix from column headers "
        "so Hive CREATE TABLE statements are clean (``first_name`` rather "
        "than ``business_data.first_name``).",
        "",
        "2. **Dropped** columns whose names match the paired-obfuscation "
        "pattern ``^(attr|field|key|code|var|ref|data|col)_\\d+(_\\d+)*$``. "
        "These columns carry the ground-truth code *in their name*, making "
        "them a synth-generator artifact rather than schema a production "
        "system would ever see. Every dropped column is a duplicate of the "
        "preceding clean-named column (same values; only the name differs).",
        "",
        "The ``annotations.csv`` vocabulary is unchanged.",
        "",
        "## Per-table cleanup counts",
        "",
        "| Table | Columns kept | Columns dropped |",
        "|---|---|---|",
    ]
    for name, kept, dropped in totals:
        readme_lines.append(f"| {name} | {kept} | {dropped} |")
    readme_lines += [
        "",
        "## Fair-comparison intent",
        "",
        "Both the Atelier DST-fused pipeline (recorded in "
        "``build/results/323cfbbc/``) and Gopala's LLM-only Agent-Studio "
        "workflow should be run against this cleaned dataset so the "
        "accuracy comparison isn't inflated by obfuscated-name leakage. "
        "The columns that remain are the ones where a classifier genuinely "
        "has to work from values + name morphology + context — not from "
        "ground truth hidden in the column header.",
        "",
        "Ground-truth labels for evaluation live in ``annotations.csv`` and "
        "can be associated back to columns via name-matching against the "
        "``Annotation`` or ``Ontology`` fields there.",
    ]
    (out_dir / "README.md").write_text("\n".join(readme_lines) + "\n")

    # 4. Zip for hand-off.
    zip_path = Path("build/meta-tagging-clean.zip")
    if zip_path.exists():
        zip_path.unlink()
    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for p in sorted(out_dir.rglob("*")):
            if p.is_file():
                zf.write(p, arcname=p.relative_to(out_dir.parent))

    # 5. Summary
    total_kept = sum(k for _, k, _ in totals)
    total_dropped = sum(d for _, _, d in totals)
    log.info("output   : %s", out_dir)
    log.info("zip      : %s (%d bytes)", zip_path, zip_path.stat().st_size)
    log.info("totals   : %d columns kept, %d dropped across %d tables",
             total_kept, total_dropped, len(totals))
    return 0


if __name__ == "__main__":
    sys.exit(main())
